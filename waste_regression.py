import warnings; warnings.filterwarnings('ignore', category=FutureWarning)
import pandas as pd, numpy as np
import statsmodels.api as sm
from statsmodels.stats.stattools import durbin_watson
from statsmodels.stats.diagnostic import acorr_breusch_godfrey, acorr_ljungbox
from statsmodels.graphics.tsaplots import plot_acf, plot_pacf
import matplotlib.pyplot as plt
import seaborn as sns
from google.colab import files

uploaded = files.upload()

names = list(uploaded.keys())
F_TRAIN = next(f for f in names if 'train' in f.lower())
F_TEST  = next(f for f in names if 'test'  in f.lower())
F_FULL  = next(f for f in names if f not in (F_TRAIN, F_TEST))
print('Full data :', F_FULL, '\nTraining  :', F_TRAIN, '\nTesting   :', F_TEST)

CATEGORIES = ['Organic', 'Inorganic']
TOTAL = {'Organic': 'TOTAL_ORGANIC', 'Inorganic': 'TOTAL_INORGANIC'}

DATA  = {k: pd.read_excel(F_FULL,  sheet_name=k) for k in CATEGORIES}   # full data (730 days)
TRAIN = {k: pd.read_excel(F_TRAIN, sheet_name=k) for k in CATEGORIES}   # training data
TEST  = {k: pd.read_excel(F_TEST,  sheet_name=k) for k in CATEGORIES}   # testing data (last 90 days)

for k, df in DATA.items():
    y = df[TOTAL[k]]
    print(f'{k}: n = {len(df)} | train {len(TRAIN[k])} | test {len(TEST[k])} | '
          f'mean = {y.mean():.1f} kg | min = {y.min():.1f} | max = {y.max():.1f} | SD = {y.std():.1f}')

"""## 1. Linear regression (full data)"""

def metrics(y, p):
    e = np.asarray(y) - np.asarray(p)
    return dict(MAE=np.mean(np.abs(e)),
                RMSE=np.sqrt(np.mean(e**2)),
                MAPE=np.mean(np.abs(e / np.asarray(y))) * 100)

models, rows = {}, []
for k, df in DATA.items():
    col = TOTAL[k]
    X = sm.add_constant(df['DAY_T'])
    m = sm.OLS(df[col], X).fit()
    models[k] = m
    df['Predicted'] = m.predict(X)
    df['Residuals'] = df[col] - df['Predicted']
    mt = metrics(df[col], df['Predicted'])
    rows.append([k, m.params['const'], m.params['DAY_T'], m.rsquared,
                 m.pvalues['DAY_T'], mt['MAE'], mt['RMSE'], mt['MAPE']])
    print(f'===== {k} =====')
    print(m.summary().tables[1])
    print(f"R = {np.sqrt(m.rsquared):.3f} | R2 = {m.rsquared:.3f} | F = {m.fvalue:.1f} "
          f"| df = (1, {int(m.df_resid)}) | p = {m.f_pvalue:.3g}\n")

results = pd.DataFrame(rows, columns=['Category', 'Beta0', 'Beta1 (kg/day)', 'R2', 'p (Day_t)',
                                      'MAE (kg)', 'RMSE (kg)', 'MAPE (%)'])
results.round(3)

