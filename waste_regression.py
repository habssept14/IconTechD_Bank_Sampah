"""## 3. Autocorrelation test (residuals of the regression in Section 1)
- **Durbin-Watson**: ≈ 2 means no autocorrelation; < 1.5 positive autocorrelation; > 2.5 negative autocorrelation.
- **Breusch-Godfrey** (lags = 7, one weekly cycle): H0 = no autocorrelation up to lag 7. p < 0.05 → autocorrelation detected.
- **Ljung-Box** (lags 7, 14, 30): H0 = residuals are white noise (no autocorrelation). p < 0.05 → autocorrelation detected.
- **ACF/PACF plot**: bars outside the blue band indicate significant autocorrelation at that lag.
"""

BG_LAGS = 7
LB_LAGS = [7, 14, 30]
ALPHA = 0.05
fmt_p = lambda p: '<0.001' if p < 0.001 else f'{p:.3f}'   # p-value display

def dw_verdict(d):
    if d < 1.5: return 'Positive autocorrelation'
    if d > 2.5: return 'Negative autocorrelation'
    return 'No autocorrelation'

ac_rows, lb_rows = [], []
for k, df in DATA.items():
    res = df['Residuals']
    dw = durbin_watson(res)
    lag1 = res.autocorr(lag=1)
    bg_lm, bg_p, bg_f, bg_fp = acorr_breusch_godfrey(models[k], nlags=BG_LAGS)
    ac_rows.append([k, lag1, dw, dw_verdict(dw), bg_lm, fmt_p(bg_p),
                    'Autocorrelation detected' if bg_p < ALPHA else 'No autocorrelation'])
    lb = acorr_ljungbox(res, lags=LB_LAGS, return_df=True)
    for lag, r in lb.iterrows():
        lb_rows.append([k, lag, r['lb_stat'], fmt_p(r['lb_pvalue']),
                        'Autocorrelation detected' if r['lb_pvalue'] < ALPHA else 'No autocorrelation'])

ac_table = pd.DataFrame(ac_rows, columns=['Category', 'Lag-1 autocorr.', 'Durbin-Watson', 'DW interpretation',
                                          f'Breusch-Godfrey LM (lags={BG_LAGS})', 'BG p-value', 'BG conclusion'])
lb_table = pd.DataFrame(lb_rows, columns=['Category', 'Lag', 'Ljung-Box Q', 'p-value', 'Conclusion'])
display(ac_table.round(4))
display(lb_table.round(4))

fig, axes = plt.subplots(2, 2, figsize=(10, 6))
for i, (k, df) in enumerate(DATA.items()):
    plot_acf(df['Residuals'], lags=40, ax=axes[i, 0], title=f'ACF - {k} residuals')
    plot_pacf(df['Residuals'], lags=40, ax=axes[i, 1], method='ywm', title=f'PACF - {k} residuals')
    for a in axes[i]:
        a.set_xlabel('Lag (days)')
fig.tight_layout(); plt.show()
savefig(fig, 'autocorrelation_acf_pacf.png')

"""## 4. Training & testing forecast (train: training file, test: testing file = last 90 days)"""

H = 90   # length of the testing data (days)
oos_rows, oos_pred = [], {}
for k in DATA:
    col = TOTAL[k]
    tr, te = TRAIN[k], TEST[k]

    # Deteksi nama kolom hari (bisa DAY_T atau HARI_T)
    tr_day_col = 'DAY_T' if 'DAY_T' in tr.columns else 'HARI_T'
    te_day_col = 'DAY_T' if 'DAY_T' in te.columns else 'HARI_T'

    m = sm.OLS(tr[col], sm.add_constant(tr[tr_day_col])).fit()
    p_te = m.predict(sm.add_constant(te[te_day_col], has_constant='add'))
    mt = metrics(te[col], p_te)
    r2_te = 1 - np.sum((te[col] - p_te)**2) / np.sum((te[col] - te[col].mean())**2)
    oos_rows.append([k, m.rsquared, r2_te, mt['MAE'], mt['RMSE'], mt['MAPE'], 100 - mt['MAPE']])
    oos_pred[k] = pd.DataFrame({te_day_col: te[te_day_col], 'DATE': te['DATE'] if 'DATE' in te.columns else te['TANGGAL'],
                                'ACTUAL': te[col].round(1), 'PREDICTED': p_te.round(1),
                                'ERROR': (te[col] - p_te).round(1)})

oos = pd.DataFrame(oos_rows, columns=['Category', 'R2 train', 'R2 test', 'MAE test (kg)', 'RMSE test (kg)',
                                      'MAPE test (%)', 'Accuracy (100-MAPE, %)'])
oos.round(3)

fig, axes = plt.subplots(2, 1, figsize=(8, 7))
for ax, k in zip(axes, DATA):
    df, col = DATA[k], TOTAL[k]
    n = len(df); tr = TRAIN[k]
    m = sm.OLS(tr[col], sm.add_constant(tr['DAY_T'])).fit()
    pred = m.predict(sm.add_constant(df['DAY_T']))
    ax.plot(df['DAY_T'], df[col], color='#9bb7d4', lw=0.7, label='Actual')
    ax.plot(df['DAY_T'], pred, color='#1f4e79', lw=1.8, label=f'Linear fit (trained on day 1-{len(tr)})')
    ax.plot(df['DAY_T'].iloc[n-H:], pred.iloc[n-H:], color='#c0392b', lw=2.2,
            label=f'Test prediction (day {len(tr)+1}-{n})')
    ax.axvspan(df['DAY_T'].iloc[n-H], df['DAY_T'].iloc[-1], color='#f5d5d0', alpha=0.4)
    ax.set_title(f'{k} waste'); ax.set_xlabel('Day (t)'); ax.set_ylabel('Volume (kg/day)')
    ax.legend(fontsize=7, loc='upper left'); ax.grid(alpha=0.3)
fig.tight_layout(); plt.show()
savefig(fig, 'out_of_sample_90days.png')

